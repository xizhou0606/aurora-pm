// Registry is the only source of truth; emit only used offline glyphs.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const webRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const repoRoot = path.resolve(webRoot, '../..')
const registry = JSON.parse(fs.readFileSync(path.join(webRoot, 'src/shared/ui/icons/registry.json'), 'utf8'))
const collection = JSON.parse(fs.readFileSync(path.join(webRoot, 'node_modules/@iconify-json/hugeicons/icons.json'), 'utf8'))
const componentOf = id => `Huge${id.split(':')[1].split('-').map(part => part[0].toUpperCase() + part.slice(1)).join('')}`
const ids = [...new Set(['mappings', 'menuActive', 'emptyStates', 'aliases'].flatMap(group => Object.values(registry[group])))].sort()
const glyphs = ids.map(id => {
  if (!id.startsWith('hugeicons:')) throw new Error(`Unsupported icon family: ${id}`)
  const glyph = collection.icons[id.slice('hugeicons:'.length)]
  if (!glyph) throw new Error(`Unknown Hugeicons glyph: ${id}`)
  if (/<(?:script|foreignObject)|\bon\w+=|(?:href|url\()/i.test(glyph.body)) throw new Error(`Unsafe glyph: ${id}`)
  return `  ${JSON.stringify(id)}: ${JSON.stringify({body: glyph.body, width: glyph.width ?? collection.width, height: glyph.height ?? collection.height})},`
})
const header = '// GENERATED by scripts/generate-icons.mjs from registry.json — DO NOT EDIT.\n'
fs.writeFileSync(path.join(webRoot, 'src/shared/ui/icons/icons.data.ts'), `${header}// Hugeicons Stroke Rounded, MIT; offline data from @iconify-json/hugeicons.
export type IconData = { body: string; width: number; height: number }
export const ICON_DATA = {
${glyphs.join('\n')}
} as const satisfies Record<string, IconData>
export type GeneratedIconName = keyof typeof ICON_DATA
`)
fs.writeFileSync(path.join(webRoot, 'src/shared/ui/icons/icons.generated.tsx'), `${header}import { Icon, type GeneratedIconName, type IconComponentProps } from './icon'
import type { ComponentType } from 'react'
function defineIcon(name: GeneratedIconName): ComponentType<IconComponentProps> {
  const Component = (props: IconComponentProps) => <Icon name={name} {...props} />
  Component.displayName = name
  return Component
}
${ids.map(id => `export const ${componentOf(id)} = defineIcon(${JSON.stringify(id)})`).join('\n')}
// Existing API aliases point to Hugeicons components; no Phosphor glyphs remain.
${Object.entries(registry.aliases).map(([name,id])=>`export const ${name} = ${componentOf(id)}`).join('\n')}
`)
const table = group => Object.entries(registry[group]).map(([name,id])=>`| ${name} | \`${id}\` | \`${componentOf(id)}\` |`).join('\n')
fs.writeFileSync(path.join(repoRoot,'docs/ICON_MIGRATION.md'), `<!-- GENERATED by apps/web/scripts/generate-icons.mjs; edit registry.json. -->
# Hugeicons Rounded 映射

唯一渲染来源：Hugeicons Stroke Rounded（MIT），Iconify 离线分发。品牌、第三方登录标识和业务画布图形保留。

${['mappings','menuActive','emptyStates','aliases'].map(group=>`## ${group}\n\n| 语义 / 兼容名 | 图标 | 组件 |\n| --- | --- | --- |\n${table(group)}`).join('\n\n')}
`)
console.log(`generate-icons: ${ids.length} Hugeicons glyphs, ${Object.keys(registry.aliases).length} compatible exports`)
